#!/usr/bin/env python3
"""Generate kernel/bteq_table.h: the filter tables of the Bluetooth sound filter.

    python3 tools/gen_bteq_table.py            write kernel/bteq_table.h
    python3 tools/gen_bteq_table.py --check    fail if the file on disk differs (make test)

Why a table: the kernel module never does floating point (the kernel does not save the
floating-point registers for a module's code), and the filter's coefficients depend only on
(band, gain step). So every one is computed here, in double precision, and the module only
looks them up.

The five bands are a low shelf, three peaks and a high shelf (one 5-band equaliser, +-12 dB in
1 dB steps) at 100 / 300 / 875 / 2400 / 6900 Hz, taken at the 48 kHz the console mixes at. The
peak width is chosen: the three peaks are about 1.5 octaves apart, and Q = 0.9 (a bandwidth of
about 1.5 octaves) makes neighbours cross near their half-gain points, which is how a graphic
equaliser with such spacing is normally built. Shelves use the cookbook slope S = 1. To change
the voicing, change CENTRE_HZ, PEAK_Q or SHELF_S below and rerun; the host test checks the
result.

Tables (all integer):
  BQ_COEF[band][gain + 12][5]   b0 b1 b2 a1 a2, Q3.29 (a0 divided out), for y = b.x - a.y.
                                Q2.30 cannot hold the shelves' b0 (up to about 2.9).
  BQ_RESP[band][gain + 12][P]   magnitude response in 1/8 dB at P log-spaced probe
                                frequencies: the worker adds the five bands up to find
                                the true peak of the cascade for the pre-gain.
  BQ_PREGAIN[k]                 10^(-k/40) in Q30: the pre-gain for k half-dB steps (0..48).
"""
import cmath
import math
import os
import sys

FS = 48000.0
CENTRE_HZ = (100.0, 300.0, 875.0, 2400.0, 6900.0)
IS_SHELF = (True, False, False, False, True)   # band 0 low shelf, band 4 high shelf
PEAK_Q = 0.9
SHELF_S = 1.0
GAIN_MIN, GAIN_MAX = -12, 12
QBITS = 29
N_PROBE = 60
PROBE_F0 = 20.0
PROBE_STEP_OCT = 1.0 / 6.0
RESP_UNIT_DB = 1.0 / 8.0
PREGAIN_STEPS = 48          # half dB each: up to 24 dB


def rbj(band, gain_db):
    """Cookbook coefficients (b0 b1 b2 a1 a2, a0 divided out)."""
    a = 10.0 ** (gain_db / 40.0)
    w0 = 2.0 * math.pi * CENTRE_HZ[band] / FS
    cs, sn = math.cos(w0), math.sin(w0)
    if not IS_SHELF[band]:
        alpha = sn / (2.0 * PEAK_Q)
        b = (1 + alpha * a, -2 * cs, 1 - alpha * a)
        aa = (1 + alpha / a, -2 * cs, 1 - alpha / a)
    else:
        alpha = sn / 2.0 * math.sqrt((a + 1 / a) * (1 / SHELF_S - 1) + 2)
        t = 2 * math.sqrt(a) * alpha
        if band == 0:      # low shelf
            b = (a * ((a + 1) - (a - 1) * cs + t), 2 * a * ((a - 1) - (a + 1) * cs),
                 a * ((a + 1) - (a - 1) * cs - t))
            aa = ((a + 1) + (a - 1) * cs + t, -2 * ((a - 1) + (a + 1) * cs), (a + 1) + (a - 1) * cs - t)
        else:              # high shelf
            b = (a * ((a + 1) + (a - 1) * cs + t), -2 * a * ((a - 1) + (a + 1) * cs),
                 a * ((a + 1) + (a - 1) * cs - t))
            aa = ((a + 1) - (a - 1) * cs + t, 2 * ((a - 1) - (a + 1) * cs), (a + 1) - (a - 1) * cs - t)
    return (b[0] / aa[0], b[1] / aa[0], b[2] / aa[0], aa[1] / aa[0], aa[2] / aa[0])


def response_db(c, f):
    z1 = cmath.exp(-2j * math.pi * f / FS)
    num = c[0] + c[1] * z1 + c[2] * z1 * z1
    den = 1 + c[3] * z1 + c[4] * z1 * z1
    return 20.0 * math.log10(abs(num / den))


def probe_freqs():
    return [PROBE_F0 * 2.0 ** (PROBE_STEP_OCT * k) for k in range(N_PROBE)]


def generate():
    out = []
    w = out.append
    w('/* GENERATED by tools/gen_bteq_table.py - do not edit; rerun the script. */')
    w('#ifndef BTT_BTEQ_TABLE_H')
    w('#define BTT_BTEQ_TABLE_H')
    w('')
    w('#include <stdint.h>')
    w('')
    w('#define BQ_GAIN_MIN   %d' % GAIN_MIN)
    w('#define BQ_GAIN_MAX   %d' % GAIN_MAX)
    w('#define BQ_GAINS      %d' % (GAIN_MAX - GAIN_MIN + 1))
    w('#define BQ_QBITS      %d      /* coefficient fraction bits (Q3.29) */' % QBITS)
    w('#define BQ_N_PROBE    %d' % N_PROBE)
    w('#define BQ_PROBE_F0   %d      /* Hz, then %.4g octave steps */' % (PROBE_F0, PROBE_STEP_OCT))
    w('#define BQ_PREGAIN_STEPS %d' % PREGAIN_STEPS)
    w('')
    maxc = 0.0
    w('static const int32_t BQ_COEF[5][BQ_GAINS][5] = {')
    for band in range(5):
        w('\t{')
        for g in range(GAIN_MIN, GAIN_MAX + 1):
            c = rbj(band, g)
            maxc = max(maxc, max(abs(x) for x in c))
            q = [int(round(x * (1 << QBITS))) for x in c]
            assert all(abs(x) < 2 ** 31 for x in q), (band, g, c)
            w('\t\t{ %s },  /* %+d dB */' % (', '.join('%d' % x for x in q), g))
        w('\t},')
    w('};')
    w('')
    w('static const int8_t BQ_RESP[5][BQ_GAINS][BQ_N_PROBE] = {   /* 1/8 dB */')
    fs = probe_freqs()
    for band in range(5):
        w('\t{')
        for g in range(GAIN_MIN, GAIN_MAX + 1):
            c = rbj(band, g)
            r = [int(round(response_db(c, f) / RESP_UNIT_DB)) for f in fs]
            assert all(-128 <= x <= 127 for x in r)
            w('\t\t{ %s },' % ', '.join('%d' % x for x in r))
        w('\t},')
    w('};')
    w('')
    w('static const int32_t BQ_PREGAIN[BQ_PREGAIN_STEPS + 1] = {   /* 10^(-k/40), Q30 */')
    vals = [int(round(10.0 ** (-k / 40.0) * (1 << 30))) for k in range(PREGAIN_STEPS + 1)]
    for i in range(0, len(vals), 6):
        w('\t' + ', '.join('%d' % v for v in vals[i:i + 6]) + ',')
    w('};')
    w('')
    w('#endif')
    sys.stderr.write('largest |coefficient| = %.3f (limit 4)\n' % maxc)
    return '\n'.join(out) + '\n'


def main():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'kernel', 'bteq_table.h')
    text = generate()
    if '--check' in sys.argv:
        if not os.path.exists(path) or open(path).read() != text:
            sys.exit('bteq_table.h is out of date: run tools/gen_bteq_table.py')
        print('bteq_table.h is up to date')
        return
    with open(path, 'w') as f:
        f.write(text)
    print('wrote', os.path.normpath(path))


if __name__ == '__main__':
    main()
