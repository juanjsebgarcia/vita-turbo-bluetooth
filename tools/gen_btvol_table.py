#!/usr/bin/env python3
"""Generate kernel/btvol_table.h: the Bluetooth volume tables.

    python3 tools/gen_btvol_table.py            write kernel/btvol_table.h
    python3 tools/gen_btvol_table.py --check    fail if the file on disk differs (make test)

The Vita has 31 volume steps (0..30) and tells Bluetooth headphones the volume as a number from 0
to 127 (AVRCP absolute volume). The console's own number for step v is (v * 127 + 15) / 30:
BV_STOCK. A table maps those 31 numbers to what is sent instead, for each volume curve and each
maximum. The module only looks numbers up (no floating point in the kernel), so every table is
computed here.

Curves (t = v / 30):
  Standard            the console's own numbers
  Finer at low volume 127 * t^1.5   the low steps are quieter and closer together
  Louder at low volume 127 * t^0.7  the low steps are louder
Maximums: 100, 90, 80, 70, 60, 50 % (the table is scaled, then capped at 127 * the maximum).

Every table is strictly increasing from 0 at step 0, so no two steps send the same number: the
numbers the headphones report can be turned back into the exact step (kernel/btvol_map.c).
BV_TAB[curve * 6 + maximum][step]; table 0 (Standard, 100 %) is the console's own numbers.
"""
import os
import sys

STEPS = 31
CURVES = (("standard", None), ("finer", 1.5), ("louder", 0.7))
MAXES = (100, 90, 80, 70, 60, 50)


def stock(v):
    return (v * 127 + 15) // 30


def table(exp, pct):
    cap = (127 * pct + 50) // 100
    out = [0]
    for v in range(1, STEPS):
        base = stock(v) if exp is None else 127.0 * (v / 30.0) ** exp
        raw = int(base * pct / 100.0 + 0.5)
        out.append(max(raw, out[-1] + 1))
    for v in range(STEPS - 1, 0, -1):
        out[v] = min(out[v], cap - (STEPS - 1 - v))
    assert out[0] == 0 and all(b > a for a, b in zip(out, out[1:])) and out[-1] <= cap <= 127, (exp, pct, out)
    return out


def generate():
    w = []
    w.append('/* GENERATED by tools/gen_btvol_table.py - do not edit; rerun the script. */')
    w.append('#ifndef BTT_BTVOL_TABLE_H')
    w.append('#define BTT_BTVOL_TABLE_H')
    w.append('')
    w.append('#include <stdint.h>')
    w.append('')
    w.append('#define BV_STEPS    %d      /* the console\'s volume steps, 0..%d */' % (STEPS, STEPS - 1))
    w.append('#define BV_CURVES   %d' % len(CURVES))
    w.append('#define BV_MAXES    %d' % len(MAXES))
    w.append('#define BV_TABLES   (BV_CURVES * BV_MAXES)')
    w.append('')
    w.append('/* The console\'s number for each step: (step * 127 + 15) / 30. */')
    w.append('static const uint8_t BV_STOCK[BV_STEPS] = {')
    st = [stock(v) for v in range(STEPS)]
    for i in range(0, STEPS, 8):
        w.append('\t' + ', '.join('%d' % x for x in st[i:i + 8]) + ',')
    w.append('};')
    w.append('')
    w.append('/* BV_TAB[curve * BV_MAXES + maximum][step]: the number sent for the console\'s step. */')
    w.append('static const uint8_t BV_TAB[BV_TABLES][BV_STEPS] = {')
    for name, exp in CURVES:
        for pct in MAXES:
            t = table(exp, pct)
            if name == "standard" and pct == 100:
                assert t == st
            w.append('\t{ %s },  /* %s, %d %% */' % (', '.join('%d' % x for x in t), name, pct))
    w.append('};')
    w.append('')
    w.append('#endif')
    return '\n'.join(w) + '\n'


def main():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'kernel', 'btvol_table.h')
    text = generate()
    if '--check' in sys.argv:
        if not os.path.exists(path) or open(path).read() != text:
            sys.exit('btvol_table.h is out of date: run tools/gen_btvol_table.py')
        print('btvol_table.h is up to date')
        return
    with open(path, 'w') as f:
        f.write(text)
    print('wrote', os.path.normpath(path))


if __name__ == '__main__':
    main()
